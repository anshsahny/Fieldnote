import { summarize, type EvalRun } from './summary';

/**
 * Markdown for eval/results/README.md (and the README's eval table) from the runs in
 * eval/results/*.json. Pure, so it is unit-tested; scripts/eval-report.ts does the file I/O.
 */

export interface Pricing {
  inputPerMTok: number;
  outputPerMTok: number;
  source: string;
}

/** The decision JSON is short (choice, confidence, one or two sentences): about 60 tokens. */
export const OUTPUT_TOKENS_PER_CALL = 60;

const ROUTE_LABEL: Record<string, string> = {
  only_on_device: 'On-device',
  only_in_cloud: 'Cloud',
  prefer_on_device: 'Prefer on-device',
  prefer_in_cloud: 'Prefer cloud',
};

const PLATFORM_LABEL: Record<string, string> = { ios: 'iPhone', web: 'Chrome' };

/** The newest run for each platform + route, ordered iOS first, then on-device before cloud. */
export function latestRuns(runs: EvalRun[]): EvalRun[] {
  const latest = new Map<string, EvalRun>();
  for (const r of runs) {
    const key = `${r.platform}|${r.route}|${r.device.includes('Simulator') ? 'sim' : 'device'}`;
    const prev = latest.get(key);
    if (!prev || prev.startedAt < r.startedAt) latest.set(key, r);
  }
  const order = (r: EvalRun) =>
    (r.platform === 'ios' ? 0 : 10) + (r.device.includes('Simulator') ? 5 : 0) + (r.route.includes('device') ? 0 : 1);
  return [...latest.values()].sort((a, b) => order(a) - order(b));
}

/** Cloud cost of a run in USD: prompt tokens in, a short decision out, for cloud-served turns only. */
export function cloudCost(run: EvalRun, pricing: Pricing): number {
  const cloud = run.turns.filter((t) => t.source === 'IN_CLOUD');
  const input = cloud.reduce((a, t) => a + (t.tokens ?? 0), 0);
  return (input * pricing.inputPerMTok + cloud.length * OUTPUT_TOKENS_PER_CALL * pricing.outputPerMTok) / 1_000_000;
}

const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : 'n/a');
const frac = (n: number, d: number) => `${n}/${d} (${pct(n, d)})`;
const secs = (ms?: number) => (ms === undefined ? 'n/a' : `${(ms / 1000).toFixed(ms < 10_000 ? 2 : 1)} s`);
const usd = (v: number) => (v === 0 ? '$0' : v < 0.01 ? `$${v.toFixed(4)}` : `$${v.toFixed(2)}`);

export function routeLabel(run: EvalRun): string {
  const where = run.device.includes('Simulator') ? 'iOS Simulator' : (PLATFORM_LABEL[run.platform] ?? run.platform);
  return `${where} · ${ROUTE_LABEL[run.route] ?? run.route}`;
}

export function resultsTable(runs: EvalRun[], pricing: Pricing): string {
  const rows = latestRuns(runs).map((run) => {
    const s = summarize(run.turns);
    const safety = `${s.safety.correct}/${s.safety.total}, ${s.safety.modelCalls} model calls`;
    return `| ${routeLabel(run)} | ${frac(s.choice.correct, s.choice.total)} | **${s.wrongAdvance}** | ${s.falseClarify} | ${s.errors} | ${frac(s.clarify.correct, s.clarify.total)} | ${safety} | ${s.scenarios.correct}/${s.scenarios.total} | ${secs(s.medianLatencyMs)} | ${usd(cloudCost(run, pricing))} |`;
  });
  return [
    '| Route | Right answer on clear notes | Wrong answer accepted | Asked instead of answering | Model errors | Asked on hedged notes | Safety stops | Scenarios fully right | Median latency | Cloud cost (all turns) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}

export function missesSection(runs: EvalRun[]): string {
  return latestRuns(runs)
    .map((run) => {
      const misses = run.turns.filter((t) => !t.ok);
      const lines = misses.map(
        (t) => `- ${t.scenario} turn ${t.turn} (${t.kind}): expected \`${t.expect}\`, got \`${t.outcome}\`${t.confidence !== undefined ? ` at ${t.confidence.toFixed(2)}` : ''}${t.error ? ` (${t.error.slice(0, 100)})` : ''}`,
      );
      return `### ${routeLabel(run)}\n\n${run.device}, ${run.startedAt.slice(0, 16).replace('T', ' ')} UTC, prompt v${run.promptVersion}, threshold ${run.threshold}${run.route.includes('cloud') ? `, ${run.cloudModel}` : ''}.\n\n${lines.length ? lines.join('\n') : 'No misses.'}`;
    })
    .join('\n\n');
}

export function report(runs: EvalRun[], pricing: Pricing, notes = ''): string {
  const turns = runs[0]?.turns.length ?? 0;
  return `# Diagnosis eval results

Generated by \`cd web && npm run eval:report\` from the JSON runs in this folder. Each run walks the
24 scenarios in [eval/scenarios/p6-scenarios.json](../scenarios/p6-scenarios.json) (8 per brand,
${turns} technician notes) through the app's own rules: the safety guard first (code, no model), then the
model maps the note to an allowed answer, then the clarification rule decides whether to advance.
The expected path is followed after every turn (teacher forcing), so one miss doesn't hide the rest.

${resultsTable(runs, pricing)}

- **Right answer on clear notes**: the model picked the expected answer and the app advanced.
- **Wrong answer accepted**: the app moved on with the wrong answer. This is the miss that matters;
  every other miss leaves the tech one tap away from the right path.
- **Asked instead of answering**: a clear note where the app still asked (safe, but a tap the tech
  didn't need), because the model said "unclear" or its confidence was under the threshold.
- **Model errors**: the call failed (for example Apple's on-device guardrail rejecting an ordinary
  note). In the app the tech taps the answer; on the default prefer-on-device route the cloud takes
  a second look when online.
- **Asked on hedged notes**: the note was a guess ("not sure", "maybe") and the app asked instead
  of advancing. This is the right outcome.
- **Safety stops**: notes that mention gas, CO, burning, sparking or water near power. These are
  caught by code before any model call, so the model-call count must be 0.
- **Cloud cost**: prompt tokens (estimated at 3.5 characters per token) plus about
  ${OUTPUT_TOKENS_PER_CALL} output tokens per cloud call, at $${pricing.inputPerMTok.toFixed(2)}/$${pricing.outputPerMTok.toFixed(2)} per 1M
  tokens (${pricing.source}). On-device turns cost nothing.
${notes ? `\n${notes.trim()}\n` : ''}
## Misses

${missesSection(runs)}
`;
}
