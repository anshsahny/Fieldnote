#!/usr/bin/env node
// Generates gitignored local config files from the gitignored secret sources at the repo root.
//
//   Inputs (never committed):
//     firebase-web-config.txt  - the firebaseConfig snippet copied from the Firebase console
//     .local-secrets           - KEY=VALUE lines (see .local-secrets.example)
//
//   Outputs (never committed, mode 0600):
//     web/.env.local                - VITE_FIREBASE_* + VITE_RECAPTCHA_SITE_KEY (dev + build)
//     web/.env.development.local    - VITE_APPCHECK_DEBUG_TOKEN (loaded by `vite dev` only,
//                                     so `vite build` can never inline it into dist/)
//     ios/Config/Secrets.xcconfig   - App Check debug tokens for Debug builds (sim + device)
//
// Prints key names only, never values.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...parts) => join(root, ...parts);

function fail(msg) {
  console.error(`setup-local-secrets: ${msg}`);
  process.exit(1);
}

function parseWebConfig(text) {
  const out = {};
  for (const m of text.matchAll(/(\w+)\s*:\s*["']([^"']*)["']/g)) out[m[1]] = m[2];
  return out;
}

function parseKeyValues(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    out[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

function assertSafeValue(key, value) {
  if (/[\r\n"]/.test(value)) fail(`${key} contains a newline or quote; refusing to write it.`);
  // xcconfig treats `//` as a comment start; Firebase tokens/keys never contain it.
  if (value.includes('//')) fail(`${key} contains "//", which xcconfig would truncate.`);
}

function writeSecret(relPath, header, entries, sep) {
  const file = p(relPath);
  mkdirSync(dirname(file), { recursive: true });
  const lines = [header, ...entries.map(([k, v]) => `${k}${sep}${v}`), ''];
  writeFileSync(file, lines.join('\n'), { mode: 0o600 });
  console.log(`wrote ${relPath}: ${entries.map(([k]) => k).join(', ')}`);
}

const webConfigPath = p('firebase-web-config.txt');
const secretsPath = p('.local-secrets');
if (!existsSync(webConfigPath)) fail('firebase-web-config.txt not found at repo root.');
if (!existsSync(secretsPath)) fail('.local-secrets not found at repo root.');

const web = parseWebConfig(readFileSync(webConfigPath, 'utf8'));
const secrets = parseKeyValues(readFileSync(secretsPath, 'utf8'));

const webMap = [
  ['VITE_FIREBASE_API_KEY', web.apiKey],
  ['VITE_FIREBASE_AUTH_DOMAIN', web.authDomain],
  ['VITE_FIREBASE_PROJECT_ID', web.projectId],
  ['VITE_FIREBASE_STORAGE_BUCKET', web.storageBucket],
  ['VITE_FIREBASE_MESSAGING_SENDER_ID', web.messagingSenderId],
  ['VITE_FIREBASE_APP_ID', web.appId],
  ['VITE_FIREBASE_MEASUREMENT_ID', web.measurementId ?? ''],
  ['VITE_RECAPTCHA_SITE_KEY', secrets.VITE_RECAPTCHA_SITE_KEY],
];
const required = ['VITE_FIREBASE_API_KEY', 'VITE_FIREBASE_PROJECT_ID', 'VITE_FIREBASE_APP_ID', 'VITE_RECAPTCHA_SITE_KEY'];
for (const [k, v] of webMap) {
  if (required.includes(k) && !v) fail(`missing value for ${k}`);
  assertSafeValue(k, v ?? '');
}

const tokens = {
  VITE_APPCHECK_DEBUG_TOKEN: secrets.VITE_APPCHECK_DEBUG_TOKEN,
  FN_APPCHECK_DEBUG_TOKEN_SIMULATOR: secrets.IOS_SIM_APPCHECK_DEBUG_TOKEN,
  FN_APPCHECK_DEBUG_TOKEN_DEVICE: secrets.IOS_DEVICE_APPCHECK_DEBUG_TOKEN,
};
for (const [k, v] of Object.entries(tokens)) {
  if (!v) fail(`missing App Check debug token for ${k}`);
  assertSafeValue(k, v);
}

const banner = 'Generated by scripts/setup-local-secrets.mjs. Gitignored. Do not commit.';

writeSecret('web/.env.local', `# ${banner}`, webMap, '=');
// Demo account passwords (written to .local-secrets by `npm run seed`); optional.
const demo = [
  ['VITE_DEMO_DISPATCHER_PASSWORD', secrets.DEMO_DISPATCHER_PASSWORD],
  ['VITE_DEMO_TECH_PASSWORD', secrets.DEMO_TECH_PASSWORD],
].filter(([, v]) => v);
demo.forEach(([k, v]) => assertSafeValue(k, v));

writeSecret(
  'web/.env.development.local',
  `# ${banner}\n# Dev server only: Vite does not load this file for production builds.`,
  [['VITE_APPCHECK_DEBUG_TOKEN', tokens.VITE_APPCHECK_DEBUG_TOKEN], ...demo],
  '=',
);
writeSecret(
  'ios/Config/Secrets.xcconfig',
  `// ${banner}\n// Included (optionally) by Debug.xcconfig only; Release builds never see these.`,
  [
    ['FN_APPCHECK_DEBUG_TOKEN_SIMULATOR', tokens.FN_APPCHECK_DEBUG_TOKEN_SIMULATOR],
    ['FN_APPCHECK_DEBUG_TOKEN_DEVICE', tokens.FN_APPCHECK_DEBUG_TOKEN_DEVICE],
  ],
  ' = ',
);
